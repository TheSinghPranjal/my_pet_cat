// The home-screen widget kitten's little routine: sit, lick her paw, meow,
// walk over to her wool ball, tap it, look happy, and stroll back.
//
// The cat images are rendered from the game's own painters, centred in a
// 104x88 unit box (the cat's 100x85 box plus a margin). Android plays the
// routine as a flip-book (generated below); the iOS widget plays the same
// beats on its timeline (see ios/PetWidget/PetWidget.swift).
import 'dart:math' as math;

import 'package:flutter/painting.dart';
import 'package:my_pet_cat/game/animations/cat_animations.dart';
import 'package:my_pet_cat/game/models/cat_game_state.dart';

/// Cat-only images, by name (`widget_cat_<name>`).
final catFrames = <String, CatFrame>{
  'idle': _at(CatPose.idle, 0.2),
  'blink': const CatFrame(eyeOpen: 0, tailAngle: 0.1),
  // Paw down, licking with the tongue out, paw down again.
  'lick_1': _at(CatPose.lick, 0.35),
  'lick_2': _at(CatPose.lick, 0.66),
  'lick_3': _at(CatPose.lick, 0.92),
  // Head up, mouth wide: "Meow!"
  'meow': const CatFrame(
    headOffset: Offset(1, -1.5),
    headTilt: -0.14,
    mouth: CatMouth.open,
    eyeScale: 1.05,
    tailAngle: 0.35,
    earTwitch: 0.1,
  ),
  for (var i = 0; i < 4; i++) 'walk_${i + 1}': _walk(i * math.pi / 2),
  'tap': const CatFrame(
    bodyLift: 1.5,
    headOffset: Offset(2, 2),
    raisedPaw: Offset(93, 78),
    gaze: 1,
    gazeY: 1,
    mouth: CatMouth.open,
    tailAngle: 0.3,
  ),
  'happy': const CatFrame(happyEyes: true, mouth: CatMouth.tongue, tailAngle: 0.35, sparkle: 0.17),
  'tail': const CatFrame(tailAngle: 0.45, gaze: -0.4),
};

CatFrame _at(CatPose pose, double t) =>
    catFrameFor(pose: pose, time: 1.0 + t, poseTime: t, walkPhase: 0, gaze: 0, swipe: 0);

CatFrame _walk(double phase) {
  // The walking pose without its speed lines; the flip-book shows the motion.
  final f = catFrameFor(pose: CatPose.walk, time: 1, poseTime: 0, walkPhase: phase, gaze: 0, swipe: 0);
  return CatFrame(
    breath: f.breath,
    bodyLift: f.bodyLift,
    headOffset: f.headOffset,
    feet: f.feet,
    tailAngle: f.tailAngle,
    mouth: CatMouth.smile,
  );
}

/// The "Meow!" bubble: none, popping in, or full size.
enum Bubble { none, pop, full }

/// One flip-book frame: which cat image, how far along the floor (0 = her
/// spot, 1 = at the ball), which way she faces, and the meow bubble.
typedef RoutineFrame = (String cat, double x, int facing, Bubble bubble);

List<RoutineFrame> _repeat(int n, RoutineFrame f) => List.filled(n, f);

List<RoutineFrame> _walkTo(double from, double to, int facing, int frames) => [
  for (var i = 0; i < frames; i++) ('walk_${i % 4 + 1}', from + (to - from) * (i + 1) / frames, facing, Bubble.none),
];

/// The whole routine, at [flipMillis] per frame (about 16 seconds a loop).
final routine = <RoutineFrame>[
  ..._repeat(4, ('idle', 0, 1, Bubble.none)),
  ('blink', 0, 1, Bubble.none),
  ..._repeat(3, ('idle', 0, 1, Bubble.none)),
  // A good wash.
  for (final n in [1, 2, 3, 2, 3, 2, 3, 1]) ('lick_$n', 0, 1, Bubble.none),
  ..._repeat(2, ('idle', 0, 1, Bubble.none)),
  // Meow!
  ('meow', 0, 1, Bubble.pop),
  ..._repeat(4, ('meow', 0, 1, Bubble.full)),
  ..._repeat(2, ('idle', 0, 1, Bubble.full)),
  ..._repeat(2, ('idle', 0, 1, Bubble.none)),
  // Roam over to the ball and give it a tap.
  ..._walkTo(0, 1, 1, 12),
  ..._repeat(3, ('tap', 1, 1, Bubble.none)),
  ..._repeat(4, ('happy', 1, 1, Bubble.none)),
  // Stroll back and settle.
  ..._walkTo(1, 0, -1, 12),
  ('blink', 0, -1, Bubble.none),
  ..._repeat(4, ('tail', 0, 1, Bubble.none)),
];

const flipMillis = 250;

/// Share of the kitten area's width the cat takes, how far she can roam
/// (both in percent), and the ball's share at the right.
const catWeight = 62;
const roamWeight = 24;
const ballWeight = 14;

/// The Android flip-book: one child per frame, each placing the cat with
/// layout weights (RemoteViews can't move views at run time).
String kittenLayoutXml() {
  final b = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- GENERATED by tool/widget_assets/render_widget_assets_test.dart from')
    ..writeln('     tool/widget_assets/widget_routine.dart. Do not edit by hand.')
    ..writeln()
    ..writeln('     The kitten\'s routine as a flip-book the launcher plays by itself (no')
    ..writeln('     app wake-ups; launchers pause it while the widget is off screen). Each')
    ..writeln('     frame places the cat along the floor with layout weights. -->')
    ..writeln('<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"')
    ..writeln('    android:layout_width="match_parent"')
    ..writeln('    android:layout_height="match_parent"')
    ..writeln('    android:importantForAccessibility="noHideDescendants">')
    ..writeln()
    ..writeln('    <LinearLayout')
    ..writeln('        android:layout_width="match_parent"')
    ..writeln('        android:layout_height="match_parent"')
    ..writeln('        android:orientation="horizontal"')
    ..writeln('        android:weightSum="100">')
    ..writeln('        <FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="${100 - ballWeight}" />')
    ..writeln('        <ImageView android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="$ballWeight" android:scaleType="fitEnd" android:paddingBottom="4dp" android:src="@drawable/widget_wool_ball" />')
    ..writeln('    </LinearLayout>')
    ..writeln()
    ..writeln('    <ViewFlipper')
    ..writeln('        android:id="@+id/kitten_flipper"')
    ..writeln('        android:layout_width="match_parent"')
    ..writeln('        android:layout_height="match_parent"')
    ..writeln('        android:autoStart="true"')
    ..writeln('        android:flipInterval="$flipMillis">');
  for (final (i, (cat, x, facing, bubble)) in routine.indexed) {
    final before = (x * roamWeight).round();
    final after = 100 - catWeight - before;
    b
      ..writeln('        <!-- $i: $cat${facing < 0 ? ' (facing left)' : ''}${bubble == Bubble.none ? '' : ', meow bubble'} -->')
      ..writeln('        <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" android:orientation="horizontal" android:weightSum="100">')
      ..writeln('            <FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="$before" />')
      ..writeln('            <ImageView android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="$catWeight" android:scaleType="fitEnd"${facing < 0 ? ' android:scaleX="-1"' : ''} android:src="@drawable/widget_cat_$cat" />');
    if (bubble == Bubble.none) {
      b.writeln('            <FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="$after" />');
    } else {
      b
        ..writeln('            <FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="$after">')
        ..writeln('                <ImageView android:layout_width="match_parent" android:layout_height="wrap_content" android:layout_gravity="top|start" android:adjustViewBounds="true" android:scaleType="fitStart"${bubble == Bubble.pop ? ' android:padding="7dp"' : ''} android:src="@drawable/widget_meow" />')
        ..writeln('            </FrameLayout>');
    }
    b.writeln('        </LinearLayout>');
  }
  b
    ..writeln('    </ViewFlipper>')
    ..writeln('</FrameLayout>');
  return b.toString();
}

/// Frame indices the provider jumps to when the app shares a pose.
String kittenFramesXml() {
  final happy = routine.indexWhere((f) => f.$1 == 'happy');
  return '''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/widget_assets/render_widget_assets_test.dart. -->
<resources>
    <!-- First frame of the happy beat, shown right after an activity. -->
    <integer name="widget_happy_frame">$happy</integer>
</resources>
''';
}
